// Builds supabase/seed-products.sql from src/data/products.js, so the database
// catalogue always matches the app's product list.
//
//   node scripts/generate-product-seed.mjs

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { PRODUCTS } from '../src/data/products.js'

const sql = value => {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return `'${String(value).replace(/'/g, "''")}'`
}

const rows = PRODUCTS.map((p, i) => `  (${[
  sql(p.id), sql(p.name), sql(p.sub), sql(p.cat), sql(p.retail),
  p.variants ? `${sql(JSON.stringify(p.variants))}::jsonb` : 'null',
  sql(p.sku), sql(p.blurb), sql(p.image), 'true', i + 1,
].join(', ')})`)

const out = `-- Generated by scripts/generate-product-seed.mjs — do not edit by hand.
-- Loads the ${PRODUCTS.length} Royal Tiara products. Re-running updates names, sizes
-- and descriptions, but keeps the admin's prices, stock and photos.

insert into public.products (id, name, sub, cat, price, variants, sku, blurb, image, in_stock, sort)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  sub = excluded.sub,
  cat = excluded.cat,
  variants = excluded.variants,
  sku = excluded.sku,
  blurb = excluded.blurb,
  sort = excluded.sort;
-- Note: photos are NOT overwritten here - the admin manages them in the app.
`

const target = fileURLToPath(new URL('../supabase/seed-products.sql', import.meta.url))
writeFileSync(target, out)
console.log(`Wrote ${PRODUCTS.length} products to supabase/seed-products.sql`)
